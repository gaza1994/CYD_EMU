#!/usr/bin/env python3
"""Copy the firmware catalogue into assets/catalog/ and generate src/catalog_assets.rs.

    python3 tools/catalog_assets.py [CATALOG_DIR]   (default: ../catalog)

Bundles cyd-firmware.toml, templates/ and a small thumbnail per entry (from screens/<id>.png,
or the README's alternative names). Screens that are a single colour (a blank TFT) are skipped:
the gallery says "blank screen" instead of showing a black box."""
import hashlib, pathlib, shutil, sys, tomllib
from PIL import Image

root = pathlib.Path(__file__).resolve().parent.parent
cat = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else root.parent / "catalog")
out = root / "assets" / "catalog"
if out.exists():
    shutil.rmtree(out)
(out / "thumbs").mkdir(parents=True)
(out / "templates").mkdir()
shutil.copy(cat / "cyd-firmware.toml", out / "cyd-firmware.toml")
data = tomllib.loads((cat / "cyd-firmware.toml").read_text())
ALT = {"wm-hello-world": "wm-1-HelloWorld", "wm-touch-test": "wm-2-TouchTest", "tasmota32-lvgl": "tasmota"}
thumbs, templates = [], []
for e in data["entries"]:
    src = e.get("source", {})
    for f in src.get("files", []) + ([src["file"]] if "file" in src else []):
        shutil.copy(cat / f, out / f)
        templates.append(f)
    p = cat / "screens" / f"{ALT.get(e['id'], e['id'])}.png"
    if not p.exists():
        continue
    im = Image.open(p).convert("RGB")
    if len(im.getcolors(1 << 24) or [0, 0]) == 1:
        continue  # blank screen
    im.thumbnail((120, 160), Image.LANCZOS)
    im = im.quantize(64, method=Image.Quantize.MEDIANCUT).convert("RGB")
    im.save(out / "thumbs" / f"{e['id']}.png", optimize=True)
    thumbs.append(e["id"])
rs = ["// Generated by tools/catalog_assets.py; do not edit.",
      "pub const CATALOG_TOML: &str = include_str!(\"../assets/catalog/cyd-firmware.toml\");",
      "pub const TEMPLATES: &[(&str, &str)] = &["]
rs += [f"    (\"{t}\", include_str!(\"../assets/catalog/{t}\"))," for t in templates]
rs += ["];", "pub const THUMBS: &[(&str, &[u8])] = &["]
rs += [f"    (\"{t}\", include_bytes!(\"../assets/catalog/thumbs/{t}.png\"))," for t in thumbs]
rs += ["];", ""]
(root / "src" / "catalog_assets.rs").write_text("\n".join(rs))
size = sum(f.stat().st_size for f in out.rglob("*") if f.is_file())
print(f"{len(data['entries'])} entries, {len(templates)} templates, {len(thumbs)} thumbnails, {size // 1024} KB")
