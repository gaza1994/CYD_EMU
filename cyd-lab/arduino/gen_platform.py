#!/usr/bin/env python3
"""Regenerate cydlab/esp32/platform.txt for an installed esp32:esp32 core.

The cyd-lab board borrows Espressif's core by reference (build.core=esp32:esp32), but
arduino-cli then sets {runtime.platform.path} to *this* platform, and esp32's
platform.txt finds its helper scripts (gen_esp32part, boot_app0.bin, partitions/*.csv,
espota, flasher) under {runtime.platform.path}/tools. So every esp32 property that
mentions it is repeated here with the esp32 platform's own folder, derived from
{build.core.path} (= <esp32 platform>/cores/esp32).

usage: gen_platform.py [path/to/esp32/hardware/esp32/<version>/platform.txt]
"""
import glob, os, sys

HEAD = """# cyd-lab Arduino platform: emulated ESP32 "Cheap Yellow Display" boards over the network.
#
# This platform has no core of its own. Its board builds with Espressif's esp32:esp32
# core (3.x), variant and esptool, by core reference (build.core=esp32:esp32), and adds:
#   * cyd-lab-discovery: lists powered-on cyd-lab devices as `cydlab` network ports
#   * cyd-lab-monitor:   Serial Monitor over the device's rfc2217:// port
# so Arduino IDE 2 / arduino-cli upload and monitor with no COM driver.
#
# GENERATED by gen_platform.py from esp32:esp32 {ver}'s platform.txt: re-run it if a
# newer esp32 core moves things around.

name=cyd-lab (emulated CYD boards)
version=0.1.0

pluggable_discovery.required.0=builtin:serial-discovery
pluggable_discovery.required.1=builtin:mdns-discovery
pluggable_discovery.required.2=cydlab:cyd-lab-discovery
pluggable_monitor.required.cydlab=cydlab:cyd-lab-monitor

# The esp32:esp32 platform folder (build.core.path is <it>/cores/esp32).
cydlab.esp32.path={{build.core.path}}/../..
cydlab.esp32.path.windows={{build.core.path}}\\..\\..

# esp32:esp32 properties that use {{runtime.platform.path}}, pointed back at esp32's folder:
"""

def main():
    src = sys.argv[1] if len(sys.argv) > 1 else sorted(glob.glob(os.path.expanduser("~/.arduino15/packages/esp32/hardware/esp32/*/platform.txt")))[-1]
    ver = os.path.basename(os.path.dirname(src))
    out = [HEAD.format(ver=ver)]
    for line in open(src, encoding="utf-8"):
        line = line.rstrip("\n")
        if line.lstrip().startswith("#") or "=" not in line or "{runtime.platform.path}" not in line:
            continue
        out.append(line.replace("{runtime.platform.path}", "{cydlab.esp32.path}"))
    dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), "cydlab", "esp32", "platform.txt")
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {dst} from {src} ({len(out) - 1} overrides)")

if __name__ == "__main__":
    main()
